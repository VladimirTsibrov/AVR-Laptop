        void renderStart(bool showPrompt)
        {
            drawSplash(startBitmap);
            if (showPrompt)
            {
                lcd.setPrintPos(32, 61);
                lcd.print(F("press space"), modeSet);
            }
        }

        void resetStartSplash()
        {
            startPromptVisible = false;
            nextStartPromptToggle = millis() + 1000UL;
            renderStart(false);
        }

        void updateStartSplash()
        {
            if ((int32_t)(millis() - nextStartPromptToggle) < 0)
                return;
            startPromptVisible = !startPromptVisible;
            nextStartPromptToggle = millis() + 1000UL;
            renderStart(startPromptVisible);
        }

        void generate()
        {
            uint8_t *field = lcd.getFrameBuffer();
            randomState ^= micros();
            if (randomState == 0)
                randomState = 1;

            for (uint16_t i = 0; i < fieldSize; i++)
                field[i] = (uint8_t)nextRandom();
            for (uint8_t y = 0; y < 64; y++)
                lcd.markDirtyLine(y);

            stateSaved = false;
            fieldReady = true;
            screen = readyScreen;
        }

        bool iterate()
        {
            uint8_t *field = lcd.getFrameBuffer();
            bool changed = false;
            bool anyAlive = false;
            memset(rows[0], 0, rowBytes);
            memcpy(rows[1], field, rowBytes);
            memcpy(rows[2], field + rowBytes, rowBytes);

            for (uint8_t y = 0; y < 64; y++)
            {
                uint8_t nextRow[rowBytes];
                for (uint8_t byte = 0; byte < rowBytes; byte++)
                {
                    const uint8_t topLeft = byte ? rows[0][byte - 1] : 0;
                    const uint8_t middleLeft = byte ? rows[1][byte - 1] : 0;
                    const uint8_t bottomLeft = byte ? rows[2][byte - 1] : 0;
                    const uint8_t topRight = byte + 1 < rowBytes ? rows[0][byte + 1] : 0;
                    const uint8_t middleRight = byte + 1 < rowBytes ? rows[1][byte + 1] : 0;
                    const uint8_t bottomRight = byte + 1 < rowBytes ? rows[2][byte + 1] : 0;
                    nextRow[byte] = nextByte(topLeft, rows[0][byte], topRight,
                                             middleLeft, rows[1][byte], middleRight,
                                             bottomLeft, rows[2][byte], bottomRight);
                    anyAlive |= nextRow[byte] != 0;
                }
                if (memcmp(field + (uint16_t)y * rowBytes, nextRow, rowBytes) != 0)
                {
                    changed = true;
                    memcpy(field + (uint16_t)y * rowBytes, nextRow, rowBytes);
                    lcd.markDirtyLine(y);
                }

                memcpy(rows[0], rows[1], rowBytes);
                memcpy(rows[1], rows[2], rowBytes);
                if (y < 62)
                    memcpy(rows[2], field + (uint16_t)(y + 2) * rowBytes, rowBytes);
                else
                    memset(rows[2], 0, rowBytes);
            }
            return changed && anyAlive;
        }

        bool saveState()
        {
            const uint16_t beforeChecksum = fieldChecksum();
            if (stateFile)
                stateFile.close();
            sdCard.mkdir("/games/life", true);
            if (!stateFile.open("/games/life/tmp", O_RDWR | O_CREAT))
            {
                return false;
            }
            if (!stateFile.truncate(0))
            {
                stateFile.close();
                return false;
            }
            const size_t written = stateFile.write(lcd.getFrameBuffer(), fieldSize);
            const bool synced = written == fieldSize && stateFile.sync();
            stateFile.close();
            return synced;
        }

        bool restoreState()
        {
            if (stateFile)
                stateFile.close();
            if (!stateFile.open("/games/life/tmp", O_RDONLY))
            {
                return false;
            }
            const uint32_t fileSize = stateFile.fileSize();
            const size_t read = stateFile.read(lcd.getFrameBuffer(), fieldSize);
            stateFile.close();
            const bool restored = read == fieldSize;
            if (restored)
                for (uint8_t y = 0; y < 64; y++)
                    lcd.markDirtyLine(y);
            return restored;
        }

