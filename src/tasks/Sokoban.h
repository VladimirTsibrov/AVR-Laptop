        uint8_t cells[mapSize];
        uint8_t initialCells[mapSize];
        uint8_t player = 0;
        uint8_t initialPlayer = 0;
        uint8_t previousPlayer = 0;
        uint8_t movedBoxFrom = 0;
        uint8_t movedBoxTo = 0;
        uint16_t level = 0;
        Screen screen = startScreen;
        bool undoAvailable = false;
        bool previousMovePushedBox = false;
        bool startPromptVisible = false;
        uint32_t nextStartPromptToggle = 0;
        bool displayActive = true;
        uint32_t transitionStartedAt = 0;
        uint16_t transitionDots = 0;
        uint16_t transitionRandom = 0xACE1;

        static const uint16_t transitionDurationMs = 1500;
        static const uint16_t transitionDotCount = 2048;

