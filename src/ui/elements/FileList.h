#ifndef UI_FILELIST_H
#define UI_FILELIST_H

#include "List.h"
#include "../TextRef.h"
#include "../../Sdcard.h"

#define FILELIST_NAV_DEPTH 8

/**
 * @brief Компонент списка файлов и директорий с навигацией по файловой системе
 *
 * Позволяет отображать содержимое директорий SD-карты и перемещаться между ними
 */
class FileList : public List
{
public:
    /**
     * @brief Конструктор списка файлов
     * @param left Координата X левого верхнего угла
     * @param top Координата Y левого верхнего угла
     * @param width Ширина компонента в пикселях
     * @param height Высота компонента в пикселях
     */
    FileList(uint8_t left, uint8_t top, uint8_t width, uint8_t height);

    /**
     * @brief Деструктор, освобождает ресурсы (открытые файлы, фильтры)
     */
    ~FileList() override;

    /**
     * @brief Открывает директорию и сканирует её содержимое
     * @param path Путь к директории (абсолютный, начинается с '/')
     * @return true если директория открыта и просканирована успешно
     */
    bool openDir(const char *path);

    /**
     * @brief Открывает выбранный элемент (директорию или файл)
     *
     * Если выбрана директория — переходит в неё, если файл — вызывает onFileSelected().
     * Для элемента ".." возвращается в родительскую папку.
     *
     * @return true если операция выполнена успешно
     */
    bool openSelected();

    /**
     * @brief Получает полный путь к выбранному элементу
     * @param[out] buffer Буфер для записи пути
     * @param bufferSize Размер буфера
     * @return true если путь успешно записан в буфер
     */
    bool getSelectedPath(char *buffer, uint8_t bufferSize);

    /**
     * @brief Обрабатывает нажатие клавиши
     *
     * Enter — открывает выбранный элемент,
     * Backspace — возврат в родительскую директорию,
     * остальные клавиши передаются базовому классу List.
     *
     * @param key Код клавиши
     * @return true если клавиша обработана
     */
    bool onKey(uint8_t key) override;

    /**
     * @brief Получает текущий путь открытой директории
     * @return Указатель на строку с путём (заканчивается '/')
     */
    const char *getCurrentPath() const { return currentPath; }

    /**
     * @brief Получает имя выбранного элемента (без пути)
     * @param[out] buffer Буфер для записи имени
     * @param bufferSize Размер буфера
     * @return true если имя успешно записано
     */
    bool getSelectedName(char *buffer, uint8_t bufferSize);

    /**
     * @brief Выбирает элемент с заданным именем в текущем каталоге
     * @return true, если элемент найден и выбран
     */
    bool selectByName(const char *name);

    /**
     * @brief Проверяет, является ли выбранный элемент директорией
     * @return true если выбрана директория (включая "..")
     */
    bool selectedIsDir();

    /**
     * @brief Устанавливает фильтр по расширению файлов
     *
     * После установки в списке будут отображаться только файлы с указанным расширением.
     * Директории отображаются всегда. Для сброса фильтра передайте пустой TextRef.
     *
     * @param extension Расширение файла (например, ".txt" или "txt")
     * @return true если фильтр установлен успешно
     */
    bool setExtensionFilter(TextRef extension);

protected:
    /**
     * @brief Получает текст элемента списка по индексу
     *
     * Директории оборачиваются в квадратные скобки: [dirname].
     * Родительская директория отображается как [..].
     *
     * @param index Индекс элемента в списке
     * @param[out] buffer Буфер для записи текста
     * @param bufferSize Размер буфера
     * @return true если текст успешно получен
     */
    bool getItemText(uint16_t index, char *buffer, uint8_t bufferSize) override;

private:
    /**
     * @brief Состояние навигации для возврата к предыдущему уровню
     */
    struct NavState
    {
        uint16_t offset; ///< Смещение прокрутки списка
        uint8_t focused; ///< Индекс сфокусированного элемента
    };

    char currentPath[MAX_PATH_LEN];                 ///< Текущий путь директории
    uint16_t dirCount;                              ///< Количество директорий в текущей папке
    uint16_t fileCount;                             ///< Количество файлов (с учётом фильтра)
    uint8_t fileFlags;                              ///< Флаги (бит 0: есть родительская директория)
    NavState navStack[FILELIST_NAV_DEPTH];          ///< Стек состояний для навигации
    uint8_t navDepth;                               ///< Текущая глубина стека навигации
    char *extensionFilter;                          ///< Фильтр по расширению (динамическая строка)
    bool directoryOpened;                           ///< Флаг успешного открытия директории

    /**
     * @brief Сканирует содержимое текущей директории
     *
     * Подсчитывает количество директорий и файлов, обновляет флаги.
     * Применяет фильтр по расширению к файлам.
     *
     * @return true если сканирование выполнено успешно
     */
    bool scanDir();

    /**
     * @brief Вызывается после успешного выбора файла
     *
     * Виртуальный метод для переопределения в наследниках.
     * По умолчанию генерирует событие EVENT_CLICK.
     *
     * @return true если событие обработано
     */
    virtual bool onFileSelected();

    /**
     * @brief Получает информацию об элементе по индексу
     *
     * Выполняет полное сканирование директории до нужного элемента.
     * Учитывает родительскую директорию ".." и фильтр по расширению.
     *
     * @param index Индекс элемента в списке
     * @param[out] name Буфер для записи имени элемента
     * @param nameSize Размер буфера имени
     * @param[out] isDir Указатель для записи признака "является директорией" (может быть nullptr)
     * @return true если элемент найден и данные записаны
     */
    bool getEntryInfo(uint16_t index, char *name, uint8_t nameSize, bool *isDir);

    /**
     * @brief Возвращает длину текущего пути
     * @return Длина строки currentPath
     */
    uint8_t pathLen() const;

    /**
     * @brief Сохраняет текущую позицию прокрутки и фокуса в стек навигации
     *
     * При переполнении стека удаляет самое старое состояние (FIFO).
     */
    void pushNav();

    /**
     * @brief Извлекает последнее сохранённое состояние из стека навигации
     * @param[out] state Структура для записи состояния
     * @return true если состояние извлечено (стек не был пуст)
     */
    bool popNav(NavState &state);

    /**
     * @brief Обрезает currentPath до родительской директории
     *
     * Удаляет последний сегмент пути (имя директории и слэш).
     * Корневая директория "/" не изменяется.
     */
    void trimToParent();

    /**
     * @brief Открывает родительскую директорию
     *
     * Обрезает путь, сканирует директорию и восстанавливает позицию
     * прокрутки из стека навигации.
     *
     * @return true если переход выполнен успешно
     */
    bool openParent();

    /**
     * @brief Проверяет, соответствует ли имя файла текущему фильтру расширений
     * @param filename Имя файла для проверки
     * @return true если фильтр не установлен или файл соответствует фильтру
     */
    bool matchesExtension(const char *filename) const;

    /**
     * @brief Проверяет, есть ли родительская директория (не корень)
     * @return true если можно перейти на уровень вверх
     */
    bool hasParent() const { return fileFlags & 0x01; }
};

#endif
