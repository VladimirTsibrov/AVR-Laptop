#ifndef UI_LIST_H
#define UI_LIST_H

#include "../UIElement.h"

#define LIST_TEXT_BUF_SIZE 32      ///< Размер буфера для текста элемента списка
#define LIST_FLAG_BORDER 0x10      ///< Флаг отрисовки рамки вокруг списка
#define LIST_FLAG_SCROLLBAR 0x80   ///< Флаг отображения полосы прокрутки

/**
 * @brief Базовый класс списка с прокруткой и выбором элементов
 * 
 * Отображает вертикальный список текстовых элементов с возможностью прокрутки
 * и выбора. Поддерживает клавиатурную навигацию (стрелки вверх/вниз, PageUp/PageDown).
 * 
 * Содержимое элементов определяется через виртуальный метод getItemText(),
 * который должен быть переопределён в наследниках для предоставления данных.
 * Базовый класс управляет только отрисовкой, прокруткой и выбором — не хранит сами данные.
 * 
 * Наследники: ArrayList (список из массива строк), FileList (файловый менеджер),
 * Menu (контекстное меню).
 */
class List : public UIElement
{
public:
    /**
     * @brief Конструктор списка
     * @param left X-координата левого верхнего угла
     * @param top Y-координата левого верхнего угла
     * @param width Ширина списка в пикселях
     * @param height Высота списка в пикселях
     */
    List(uint8_t left, uint8_t top, uint8_t width, uint8_t height);

    /**
     * @brief Отрисовывает список на экране
     * 
     * Рисует рамку (если включена), видимые элементы и полосу прокрутки (если нужна).
     * Выделяет сфокусированный элемент инверсией.
     */
    void draw() override;
    
    /**
     * @brief Обрабатывает нажатие клавиши
     * 
     * Поддерживаемые клавиши:
     * - Вверх/Вниз: перемещение по элементам
     * - PageUp/PageDown: прокрутка на страницу
     * - Home/End: переход к первому/последнему элементу
     * - Enter: генерирует событие EVENT_CLICK
     * 
     * @param key Код клавиши
     * @return true если клавиша обработана
     */
    bool onKey(uint8_t key) override;

    /**
     * @brief Устанавливает количество элементов в списке
     * 
     * После изменения количества элементов список автоматически нормализует
     * позицию выбора и прокрутки, чтобы они оставались в допустимых пределах.
     * 
     * @param count Количество элементов
     */
    void setItemCount(uint16_t count);
    
    /**
     * @brief Получает количество элементов в списке
     * @return Количество элементов
     */
    uint16_t getItemCount() const { return itemCount; }
    
    /**
     * @brief Получает индекс выбранного элемента
     * @return Индекс выбранного элемента (0-based)
     */
    uint16_t getSelectedIndex() const;
    
    /**
     * @brief Устанавливает выбранный элемент по индексу
     * 
     * Автоматически корректирует прокрутку, чтобы выбранный элемент был виден.
     * 
     * @param index Индекс элемента для выбора
     */
    void setSelectedIndex(uint16_t index);

    /**
     * @brief Включает/выключает отрисовку рамки вокруг списка
     * @param value true — рисовать рамку
     */
    void setDrawBorder(bool value);
    
    /**
     * @brief Проверяет, отрисовывается ли рамка
     * @return true если рамка включена
     */
    bool isDrawBorder() const { return flags & LIST_FLAG_BORDER; }

    /**
     * @brief Включает/выключает полосу прокрутки
     * @param value true — показывать полосу прокрутки
     */
    void setScrollBarVisible(bool value);
    
    /**
     * @brief Проверяет, отображается ли полоса прокрутки
     * @return true если полоса прокрутки включена
     */
    bool isScrollBarVisible() const { return flags & LIST_FLAG_SCROLLBAR; }

protected:
    /**
     * @brief Получает текст элемента по индексу
     * 
     * Виртуальный метод, который должен быть переопределён в наследниках
     * для предоставления содержимого элементов списка.
     * 
     * @param index Индекс элемента (0-based)
     * @param[out] buffer Буфер для записи текста элемента
     * @param bufferSize Размер буфера
     * @return true если элемент существует и текст записан
     */
    virtual bool getItemText(uint16_t index, char *buffer, uint8_t bufferSize);
    
    /**
     * @brief Получает количество видимых строк в списке
     * @return Количество строк, помещающихся в области списка
     */
    uint8_t getVisibleRows() const;
    
    /**
     * @brief Получает X-координату левого края области содержимого
     * @return Координата X (с учётом рамки)
     */
    uint8_t getContentLeft() const;
    
    /**
     * @brief Получает Y-координату верхнего края области содержимого
     * @return Координата Y (с учётом рамки)
     */
    uint8_t getContentTop() const;
    
    /**
     * @brief Получает ширину области содержимого
     * @return Ширина в пикселях (с учётом рамки и полосы прокрутки)
     */
    uint8_t getContentWidth() const;
    
    /**
     * @brief Получает высоту области содержимого
     * @return Высота в пикселях (с учётом рамки)
     */
    uint8_t getContentHeight() const;
    
    /**
     * @brief Проверяет, нужна ли полоса прокрутки
     * @return true если элементов больше, чем видимых строк
     */
    bool needsScrollBar() const;
    
    /**
     * @brief Отрисовывает выделение сфокусированной строки
     * @param row Номер видимой строки (относительно области содержимого)
     */
    void drawFocusRow(uint8_t row);
    
    /**
     * @brief Нормализует позицию выбора и прокрутки
     * 
     * Корректирует scrollOffset и focusedRow, чтобы они не выходили
     * за границы допустимых значений.
     */
    void normalizeSelection();

    uint16_t itemCount;       ///< Общее количество элементов в списке
    uint16_t scrollOffset;    ///< Индекс первого видимого элемента
    uint8_t focusedRow;       ///< Номер сфокусированной строки (относительно видимых)
    uint8_t rowHeight;        ///< Высота одной строки в пикселях
};

#endif
